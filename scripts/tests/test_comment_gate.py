@pytest.mark.parametrize("name, text, flagged", [
    ("a subexpression inside a quoted string inside a hole", PS_NESTED, True),
    ("two backticks leave the hole open", PS_EVEN, True),
    ("three backticks escape the hole", PS_ODD, False),
])
def test_powershell_holes_agree_with_the_native_parser(tmp_path, name, text, flagged):
    errors, comments = powershell_comments(tmp_path, text)
    assert errors == 0
    assert any("PAY-123" in c for c in comments) is flagged
    assert (hits("tools/run.ps1", text) == [("tracker", 2)]) is flagged


def test_powershell_single_quoted_string_in_a_hole_stays_literal():
    text = '$s = @"\n$( \'value $(1 # PAY-123\' )\n"@\n'
    assert hits("tools/run.ps1", text) == []


def test_powershell_nested_subexpression_closes_back_into_its_string():
    text = '$s = @"\n$( "a $(1) b" ) # PAY-9 is text\n"@\n# real PAY-8\n'
    assert hits("tools/run.ps1", text) == [("tracker", 4)]


def test_scala_double_dollar_is_a_literal_dollar_not_a_hole():
    assert hits("src/A.scala", 's"""\n$${notCode // PAY-123\n}\n"""\n') == []
    assert hits("src/A.scala", 's"""\n$$$${notCode // PAY-123\n}\n"""\n') == []


def test_scala_odd_dollar_run_ends_in_a_hole():
    assert hits("src/A.scala", 's"""\n$$${code // PAY-123\n}\n"""\n') == [("tracker", 2)]
    assert hits("src/A.scala", 's"""\n${code // PAY-123\n}\n"""\n') == [("tracker", 2)]
