# ---- round 5: nested holes, backtick parity, Scala dollar escapes -------------

PS_WALK = ("function Walk($tokens) { foreach ($t in $tokens) { $t; "
           "if ($t.NestedTokens) { Walk $t.NestedTokens } } }; ")


def powershell_comments(tmp_path, text):
    """Parse errors and comment texts the native PowerShell parser finds in `text`."""
    shell = shutil.which("pwsh")
    if not shell:
        pytest.skip("pwsh is not installed")
    script = tmp_path / "fixture.ps1"
    script.write_text(text, encoding="utf-8")
    probe = (PS_WALK + "$t=$null;$e=$null;"
             f"[void][System.Management.Automation.Language.Parser]::ParseFile('{script}',[ref]$t,[ref]$e);"
             "'ERRORS=' + $e.Count; "
             f"Walk $t | Where-Object {{ $_.Kind -eq 'Comment' }} | ForEach-Object {{ 'COMMENT=' + $_.Text }}")
    run = subprocess.run([shell, "-NoProfile", "-Command", probe],
                         capture_output=True, text=True, timeout=120)
    lines = run.stdout.splitlines()
    errors = int(next(line for line in lines if line.startswith("ERRORS=")).split("=")[1])
    return errors, [line[len("COMMENT="):] for line in lines if line.startswith("COMMENT=")]


