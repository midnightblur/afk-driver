"""The pre-commit comment gate: tracker references and the 2-line cap.

The engine reads a staged diff (`git diff --cached -U0`) plus the staged blob
of each changed file, so a block comment that began in unchanged lines is still
seen as a comment. Nothing here needs a forge or a tracker.
"""
from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
from pathlib import Path

import pytest

PLUGIN_ROOT = Path(__file__).resolve().parents[2]
ENGINE = PLUGIN_ROOT / "hooks" / "lib" / "comment_gate.py"


def load():
    spec = importlib.util.spec_from_file_location("comment_gate", ENGINE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gate = load()


def check(path, before, after, *, tracker="jira", keys=""):
    """Findings for a change of one file, given its old and new text."""
    patterns = gate.load_reference_patterns(PLUGIN_ROOT, tracker, keys)
    old_lines = before.splitlines()
    new_lines = after.splitlines()
    added = [(number, text) for number, text in enumerate(new_lines, 1)
             if text not in old_lines]
    return gate.check_file(path, after, {number for number, _ in added}, patterns)


def messages(findings):
    return [finding.message for finding in findings]


